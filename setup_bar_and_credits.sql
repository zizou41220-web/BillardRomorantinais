-- 2. Ajouter la colonne 'credit_balance' sur la table 'profiles' (solde d'avance / cagnotte)
ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS credit_balance numeric DEFAULT 0;

-- 3. Créer la table 'credit_transactions' pour l'audit et l'historique complet des rechargements
CREATE TABLE IF NOT EXISTS public.credit_transactions (
    id bigint generated by default as identity primary key,
    member_id uuid references public.profiles(id) on delete cascade not null,
    amount numeric not null,
    payment_method text default 'Espèces',
    created_by_name text not null,
    note text,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Sécurité RLS pour credit_transactions
ALTER TABLE public.credit_transactions ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'credit_transactions' AND policyname = 'Allow read credit_transactions') THEN
    CREATE POLICY "Allow read credit_transactions" ON public.credit_transactions FOR SELECT USING (true);
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'credit_transactions' AND policyname = 'Allow insert credit_transactions') THEN
    CREATE POLICY "Allow insert credit_transactions" ON public.credit_transactions FOR INSERT WITH CHECK (true);
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'credit_transactions' AND policyname = 'Allow update credit_transactions') THEN
    CREATE POLICY "Allow update credit_transactions" ON public.credit_transactions FOR UPDATE USING (true);
  END IF;
END $$;

-- 4. Sécurité pour que tout profil manquant soit synchronisé avec solde initial à 0
INSERT INTO public.profiles (id, email, full_name, role, can_manage_stock, is_approved, avatar_url, credit_balance)
SELECT 
    u.id,
    u.email,
    COALESCE(NULLIF(TRIM(im.full_name), ''), split_part(u.email, '@', 1)) AS full_name,
    COALESCE(im.role, 'member') AS role,
    COALESCE(im.can_manage_stock, false) AS can_manage_stock,
    COALESCE(im.is_approved, true) AS is_approved,
    im.avatar_url,
    0
FROM auth.users u
LEFT JOIN public.imported_members im ON LOWER(TRIM(im.email)) = LOWER(TRIM(u.email))
LEFT JOIN public.profiles p ON p.id = u.id
WHERE p.id IS NULL
ON CONFLICT (id) DO NOTHING;

-- 5. Déclencheur automatique à chaque nouvelle inscription
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger AS $$
DECLARE
    imp_name text;
    imp_role text;
    imp_stock boolean;
    imp_approved boolean;
    imp_avatar text;
BEGIN
    SELECT full_name, role, can_manage_stock, is_approved, avatar_url
    INTO imp_name, imp_role, imp_stock, imp_approved, imp_avatar
    FROM public.imported_members
    WHERE LOWER(TRIM(email)) = LOWER(TRIM(new.email))
    LIMIT 1;

    INSERT INTO public.profiles (id, email, full_name, role, can_manage_stock, is_approved, avatar_url, credit_balance)
    VALUES (
        new.id,
        new.email,
        COALESCE(NULLIF(TRIM(imp_name), ''), new.raw_user_meta_data->>'full_name', split_part(new.email, '@', 1)),
        COALESCE(imp_role, 'member'),
        COALESCE(imp_stock, false),
        COALESCE(imp_approved, true),
        imp_avatar,
        0
    )
    ON CONFLICT (id) DO UPDATE SET
        full_name = COALESCE(NULLIF(TRIM(EXCLUDED.full_name), ''), public.profiles.full_name),
        role = COALESCE(EXCLUDED.role, public.profiles.role),
        can_manage_stock = COALESCE(EXCLUDED.can_manage_stock, public.profiles.can_manage_stock),
        is_approved = COALESCE(EXCLUDED.is_approved, public.profiles.is_approved),
        avatar_url = COALESCE(EXCLUDED.avatar_url, public.profiles.avatar_url);

    RETURN new;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;

CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

